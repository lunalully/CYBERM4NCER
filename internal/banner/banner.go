// Lines returns a copy of the ASCII art lines.
func Lines() []string {
	return append([]string(nil), art...)
}

// Art returns the ASCII art as a single string.
func Art() string {
	return strings.Join(art, "\n")
}

// Width returns the widest line, in runes.
func Width() int {
	width := 0
	for _, line := range art {
		if w := utf8.RuneCountInString(line); w > width {
			width = w
		}
	}
	return width
}
